def _smooth(points, rounds=2):
    """Chaikin corner cutting: turns the traced outline into smooth curves."""
    for _ in range(rounds):
        out = []
        for i, (x0, y0) in enumerate(points):
            x1, y1 = points[(i + 1) % len(points)]
            out.append((0.75 * x0 + 0.25 * x1, 0.75 * y0 + 0.25 * y1))
            out.append((0.25 * x0 + 0.75 * x1, 0.25 * y0 + 0.75 * y1))
        points = out
    return points


_RUNE_SHAPES = tuple((layer, color, tuple((hole, tuple(_smooth(list(pts)))) for hole, pts in shapes))
                     for layer, color, shapes in RUNE_ICON)


def draw_rune_icon(image, cx, cy, ux, uy):
    """Composite the rune icon onto `image` centred at (cx, cy); `ux`/`uy`
    are image pixels per icon pixel."""
    xs = [x for _layer, _color, shapes in _RUNE_SHAPES for _hole, pts in shapes for x, _y in pts]
    ys = [y for _layer, _color, shapes in _RUNE_SHAPES for _hole, pts in shapes for _x, y in pts]
    left, top = int(cx + min(xs) * ux) - 2, int(cy + min(ys) * uy) - 2
    right, bottom = int(cx + max(xs) * ux) + 3, int(cy + max(ys) * uy) + 3
    size = (right - left, bottom - top)
    if size[0] <= 0 or size[1] <= 0:
        return
    for _layer, color, shapes in _RUNE_SHAPES:
        mask = Image.new("L", size, 0)
        draw = ImageDraw.Draw(mask)
        # Two-level shapes: fill every outline, then cut every hole.
        for want_hole in (False, True):
            for is_hole, points in shapes:
                if is_hole == want_hole:
                    draw.polygon([(cx + x * ux - left, cy + y * uy - top) for x, y in points],
                                 fill=0 if is_hole else 255)
        image.paste(color, (left, top), mask)
